// Assembles mobile/www/ — the directory Capacitor copies into the native app.
//
// Deliberately NOT `webDir: "../ui"`: that would ship the .jsx sources into the
// app bundle and leave no way to give mobile a different config.js from the web
// build. Instead we copy the compiled output and write a mobile-specific config.
import { cp, mkdir, rm, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const ui = path.join(root, 'ui');
const www = path.resolve(here, '..', 'www');

const apiBase = (process.env.MB_API_BASE || '').replace(/\/+$/, '');
if (!apiBase) {
  console.error(
    'MB_API_BASE is not set.\n' +
      '  The app bundle has no server of its own, so a same-origin (empty) apiBase\n' +
      '  would make every request resolve against capacitor://localhost and fail.\n' +
      '  Set it to the deployed API, e.g.\n' +
      '    MB_API_BASE=https://medibridge.up.railway.app npm run sync\n' +
      '  or, for LAN development against a local uvicorn:\n' +
      '    MB_API_BASE=http://192.168.x.x:8000 npm run sync'
  );
  process.exit(1);
}
// Must be a real absolute origin. A bare `http://:8000` (an unset shell var in
// the middle of the string) parses as a URL but produces a bundle that can
// never reach anything, so check the host explicitly.
let parsed;
try {
  parsed = new URL(apiBase);
} catch {
  console.error(`MB_API_BASE is not a valid URL: ${apiBase}`);
  process.exit(1);
}
if (!/^https?:$/.test(parsed.protocol) || !parsed.hostname) {
  console.error(`MB_API_BASE must be http(s)://host[:port], got: ${apiBase}`);
  process.exit(1);
}
if (apiBase.startsWith('http://')) {
  console.warn(
    `warning: MB_API_BASE is cleartext (${apiBase}). Android blocks cleartext from ` +
      'API 28 without a debug network-security config, and this must never ship in a release build.'
  );
}

// Everything the app needs at runtime — sources and build tooling stay behind.
const ASSETS = ['index.html', 'styles.css', 'js', 'vendor', 'fonts'];

for (const a of ASSETS) {
  try {
    await access(path.join(ui, a));
  } catch {
    console.error(`missing ui/${a} — run \`npm run build:web\` first`);
    process.exit(1);
  }
}

await rm(www, { recursive: true, force: true });
await mkdir(www, { recursive: true });
for (const a of ASSETS) {
  await cp(path.join(ui, a), path.join(www, a), { recursive: true });
}

await writeFile(
  path.join(www, 'config.js'),
  '// Generated by mobile/scripts/prepare-www.mjs — do not edit.\n' +
    `window.MB_CONFIG = { apiBase: ${JSON.stringify(apiBase)} };\n`,
  'utf8'
);

console.log(`prepare:www -> mobile/www/ (apiBase ${apiBase})`);
